import numpy as np
import networkx as nx
from sklearn.cluster import SpectralClustering

G = nx.DiGraph()

core_sources = [f"Source_{i}" for i in range(5)]
core_sinks = [f"Sink_{i}" for i in range(5)]
true_bottleneck = "True_Intel_Bridge"

for src in core_sources:
    G.add_node(src, type="Operative", ground_truth="Core")
    G.add_edge(src, true_bottleneck, capacity=20, weight=1)
for snk in core_sinks:
    G.add_node(snk, type="Drop_Node", ground_truth="Core")
    G.add_edge(true_bottleneck, snk, capacity=20, weight=1)
G.add_node(true_bottleneck, type="Drop_Node", ground_truth="Core")

red_herring_hub = "Red_Herring_Hub"
G.add_node(red_herring_hub, type="Comms_Server", ground_truth="Noise")
for i in range(30):
    decoy_leaf = f"Decoy_Leaf_{i}"
    G.add_node(decoy_leaf, type="Operative", ground_truth="Noise")
    G.add_edge(decoy_leaf, red_herring_hub, capacity=1, weight=10)
    G.add_edge(red_herring_hub, decoy_leaf, capacity=1, weight=10)

for src in core_sources:
    G.add_edge(src, red_herring_hub, capacity=2, weight=15)

degree_centrality = nx.degree_centrality(G)
betweenness_centrality = nx.betweenness_centrality(G, weight="weight")

source_test, sink_test = "Source_0", "Sink_0"
flow_value, flow_dict = nx.maximum_flow(G, source_test, sink_test, capacity="capacity")

nodes_list = list(G.nodes())
node_index = {n: i for i, n in enumerate(nodes_list)}
cap_adj = nx.to_numpy_array(G, nodelist=nodes_list, weight="capacity")
affinity = cap_adj + cap_adj.T

sc = SpectralClustering(n_clusters=2, affinity="precomputed", random_state=42)
cluster_labels = sc.fit_predict(affinity)

print("=== INTEL NETWORK DIAGNOSIS ===")
print(f"Max Flow Capacity ({source_test} -> {sink_test}) : {flow_value} units\n")
print(f"{'Node Name' :<22} | {'Degree' :<6} | {'Betweenness' :<11} | {'Cluster' :<7} | Ground Truth")
print("-" * 70)
target_nodes = [true_bottleneck, red_herring_hub, "Source_0", "Decoy_Leaf_5"]
for node in target_nodes:
    idx = node_index[node]
    print(
        f"{node:<22} | {degree_centrality[node]:<6.3f} | "
        f"{betweenness_centrality[node]:<11.3f} | {cluster_labels[idx]:<7} | "
        f"{G.nodes[node]['ground_truth']}"
    )

core_nodes = [n for n in nodes_list if G.nodes[n]["ground_truth"] == "Core"]
noise_nodes = [n for n in nodes_list if G.nodes[n]["ground_truth"] == "Noise"]

top_by_degree = sorted(nodes_list, key=lambda n: degree_centrality[n], reverse=True)[:len(core_nodes)]
top_by_betweenness = sorted(nodes_list, key=lambda n: betweenness_centrality[n], reverse=True)[:len(core_nodes)]

print("\n=== HOW OFTEN EACH METHOD MISTAKES THE DECOY HUB FOR THE CORE ===")
print(f"Top-{len(core_nodes)} nodes by degree centrality that are actually Core: " f"{sum(1 for n in top_by_degree if n in core_nodes)}/{len(core_nodes)}")
print(f"Top-{len(core_nodes)} nodes by betweenness centrality that are actually Core: " f"{sum(1 for n in top_by_betweenness if n in core_nodes)}/{len(core_nodes)}")

core_cluster = cluster_labels[node_index[true_bottleneck]]
recovered_core = sum(1 for n in core_nodes if cluster_labels[node_index[n]] == core_cluster)
print(f"Core nodes placed in the bottleneck's spectral cluster: {recovered_core}/{len(core_nodes)}")